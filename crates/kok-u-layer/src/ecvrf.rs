// TEST-ONLY PROVE COUNTER. `prove()` costs about 0.87 ms under this build
// because four P-256 scalar multiplications are the bulk of it (measured:
// 1.499 ms for the four mults, 0.05 ms for everything else). A test that
// proves over N tasks therefore has a cost you can predict from N alone, so
// the way to guard a performance property of the assignment tests is to
// count proves, not to measure seconds — a wall-clock threshold flakes with
// machine load, and this machine has run at a load average of ~13.4 while
// these tests were being timed.
//
// Thread-local on purpose. The test binary runs its tests on a thread pool,
// so a process-global counter would accumulate another test's proves and
// make the count meaningless; a thread-local counter sees only the proves
// the test that reset it made on its own thread. (A doc comment cannot
// attach to a macro item, which is why this is an ordinary comment.)
#[cfg(test)]
thread_local! {
    static PROVE_COUNT: std::cell::Cell<u64> = const { std::cell::Cell::new(0) };
}

/// Read and reset the prove counter. Returns how many proves ran on this
/// thread since the last reset.
#[cfg(test)]
pub(crate) fn take_prove_count() -> u64 {
    PROVE_COUNT.with(|c| c.replace(0))
}

/// suite_string for ECVRF-P256-SHA256-TAI (RFC 9381 §5.5).
const SUITE: u8 = 0x01;
/// cLen for P-256 suites: 16 octets.
const CLEN: usize = 16;
/// fLen = qLen = 32 for P-256; ptLen = fLen + 1 with compression.
const QLEN: usize = 32;
const PTLEN: usize = 33;
/// The order of the P-256 group, for the s < q bound in decode_proof and
/// the mod-q reduction in RFC 6979 nonce generation.
const Q: [u8; 32] = [
    0xFF, 0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x00, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xBC, 0xE6, 0xFA, 0xAD, 0xA7, 0x17, 0x9E, 0x84, 0xF3, 0xB9, 0xCA, 0xC2, 0xFC, 0x63, 0x25, 0x51,
];

type HmacSha256 = Hmac<Sha256>;

/// OS2IP over a value that fits in u128. Only ever called on the 16-byte
/// challenge; 32-byte values are reduced mod q first (see `mod_q`).
fn string_to_int(s: &[u8]) -> u128 {
    let mut out = 0u128;
    for &b in s {
        out = out * 256 + b as u128;
    }
    out
}

/// I2OSP: a non-negative integer to a fixed-length big-endian octet string.
fn int_to_string(a: u128, len: usize) -> Vec<u8> {
    assert!(len <= 16, "int_to_string is only used for the 16-byte challenge");
    let mut out = vec![0u8; len];
    let mut v = a;
    for i in (0..len).rev() {
        out[i] = (v & 0xFF) as u8;
        v >>= 8;
    }
    assert_eq!(v, 0, "the value did not fit in the requested length");
    out
}

/// RFC 6979 bits2octets for P-256: z2 = OS2IP(h1) mod q. Because q is just
/// over 2^255 and h1 is at most 2^256-1, h1 < 2q always, so a single
/// compare-and-subtract suffices — no big-integer library needed.
fn mod_q(bytes: &[u8; 32]) -> [u8; 32] {
    if &bytes[..] < &Q[..] {
        return *bytes;
    }
    // h1 - q, big-endian, where h1 < 2q guarantees no second borrow
    let mut out = [0u8; 32];
    let mut borrow = 0i32;
    for i in (0..32).rev() {
        let diff = bytes[i] as i32 - Q[i] as i32 - borrow;
        if diff < 0 {
            out[i] = (diff + 256) as u8;
            borrow = 1;
        } else {
            out[i] = diff as u8;
            borrow = 0;
        }
    }
    out
}

fn point_to_string(p: &AffinePoint) -> Vec<u8> {
    p.to_encoded_point(true).as_bytes().to_vec()
}

fn string_to_point(s: &[u8]) -> Option<AffinePoint> {
    if s.len() != PTLEN {
        return None;
    }
    let ep = EncodedPoint::from_bytes(s).ok()?;
    AffinePoint::from_encoded_point(&ep).into_option()
}

/// Decode a 32-byte big-endian value into a P-256 scalar, rejecting
/// anything that is not canonically less than q.
fn scalar_from_bytes(b: &[u8; 32]) -> Option<Scalar> {
    Scalar::from_repr(FieldBytes::from(*b)).into_option()
}

/// A challenge or any small integer (c < 2^128 < q) as a scalar.
fn scalar_from_int(v: u128) -> Scalar {
    let mut arr = [0u8; 32];
    let be = int_to_string(v, 16);
    arr[16..].copy_from_slice(&be);
    scalar_from_bytes(&arr).expect("c < 2^128 is always a valid scalar")
}

/// The base point B as a projective point.
fn generator() -> ProjectivePoint {
    ProjectivePoint::from(AffinePoint::GENERATOR)
}

/// SHA-256 over concatenated slices, without building one big Vec.
fn hash_chunks(chunks: &[&[u8]]) -> [u8; 32] {
    let mut h = Sha256::new();
    for c in chunks {
        h.update(c);
    }
    h.finalize().into()
}

/// RFC 9381 §5.4.1.1, with interpret_hash_value_as_a_point(s) =
/// string_to_point(0x02 || s) and encode_to_curve_salt = PK_string.
fn encode_to_curve(pk_string: &[u8], alpha: &[u8]) -> AffinePoint {
    let mut ctr = 0u8;
    loop {
        let ctr_slice = [ctr];
        let digest = hash_chunks(&[&[SUITE, 0x01], pk_string, alpha, &ctr_slice, &[0x00]]);
        // try to read the digest as the x-coordinate of an even-y point
        let mut candidate = [0u8; PTLEN];
        candidate[0] = 0x02;
        candidate[1..].copy_from_slice(&digest);
        if let Some(h) = string_to_point(&candidate) {
            // cofactor is 1 on P-256, so the cofactor multiplication is the
            // identity and is omitted; the identity check is implied by
            // decompression succeeding at a nonzero x
            return h;
        }
        ctr = ctr.wrapping_add(1);
    }
}

/// RFC 9381 §5.4.3: c = the first cLen bytes of Hash over the five points.
fn challenge_generation(
    p1: &AffinePoint,
    p2: &AffinePoint,
    p3: &AffinePoint,
    p4: &AffinePoint,
    p5: &AffinePoint,
) -> u128 {
    let mut chunks: Vec<Vec<u8>> = vec![vec![SUITE, 0x02]];
    for p in [p1, p2, p3, p4, p5] {
        chunks.push(point_to_string(p));
    }
    chunks.push(vec![0x00]);
    let refs: Vec<&[u8]> = chunks.iter().map(|c| c.as_slice()).collect();
    let digest = hash_chunks(&refs);
    string_to_int(&digest[..CLEN])
}

/// RFC 6979 §3.2 deterministic nonce, as specialised by RFC 9381 §5.4.2.1:
/// the message is h_string, the hash is SHA-256, the key is the secret
/// scalar x, and the "suitable for DSA/ECDSA" check is omitted.
fn nonce_generation(sk: &[u8; 32], h_string: &[u8]) -> Scalar {
    // RFC 6979 steps 2-3: V = 0x01..0x01, K = 0x00..0x00 (hlen bytes)
    let mut v = [0x01u8; 32];
    let mut k = [0x00u8; 32];
    let x = sk;

    let mac = |key: &[u8; 32], data: &[&[u8]]| -> [u8; 32] {
        let mut m = HmacSha256::new_from_slice(key).expect("HMAC accepts any key length");
        for d in data {
            m.update(d);
        }
        let mut out = [0u8; 32];
        out.copy_from_slice(&m.finalize().into_bytes());
        out
    };

    // step 1: h1 = H(m) with m = h_string
    let h1 = hash_chunks(&[h_string]);
    // bits2octets(h1) = OS2IP(h1) mod q
    let h1_mod = mod_q(&h1);
    // int2octets(x): x is already a canonical 32-byte big-endian scalar

    // step 4: K = HMAC_K(V || 0x00 || int2octets(x) || bits2octets(h1))
    k = mac(&k, &[&v, &[0x00], x, &h1_mod]);
    // step 5: V = HMAC_K(V)
    v = mac(&k, &[&v]);
    // step 6: K = HMAC_K(V || 0x01 || int2octets(x) || bits2octets(h1))
    k = mac(&k, &[&v, &[0x01], x, &h1_mod]);
    // step 7: V = HMAC_K(V)
    v = mac(&k, &[&v]);

    // step 8: loop until a candidate nonce lies in [1, q-1]
    loop {
        // h.2: while len(T) < qlen, V = HMAC_K(V); T = T || V. qlen is 256
        // bits here and hlen is 256 bits, so exactly one round is needed.
        v = mac(&k, &[&v]);
        // c. k = bits2int(T); with qlen == hlen this is OS2IP(V)
        // d. if 1 <= k <= q-1, that is our nonce
        if v != [0u8; 32] {
            if let Some(scalar) = scalar_from_bytes(&v) {
                return scalar;
            }
        }
        // e. K = HMAC_K(V || 0x00); V = HMAC_K(V); continue
        k = mac(&k, &[&v, &[0x00]]);
        v = mac(&k, &[&v]);
    }
}

/// A VRF key pair: the secret scalar x and the public key Y = x*B.
/// On this ciphersuite SK == x (RFC 9381 §5.5).
pub struct VrfKeys {
    pub sk: [u8; 32],
    pub pk: Vec<u8>,
}

impl VrfKeys {
    pub fn from_secret(sk: [u8; 32]) -> Self {
        let x = scalar_from_bytes(&sk).expect("the secret scalar must be a valid P-256 scalar");
        let y = generator() * &x;
        let pk = point_to_string(&y.to_affine());
        Self { sk, pk }
    }
}

/// RFC 9381 §5.4.4: split a proof into (Gamma, c, s), rejecting malformed
/// input. Total — returns None rather than panicking.
pub fn decode_proof(pi: &[u8]) -> Option<(AffinePoint, u128, Scalar)> {
    if pi.len() != PTLEN + CLEN + QLEN {
        return None;
    }
    let gamma = string_to_point(&pi[..PTLEN])?;
    let c = string_to_int(&pi[PTLEN..PTLEN + CLEN]);
    let s_bytes = &pi[PTLEN + CLEN..];
    // step 8: s >= q is INVALID. Both are 32-byte big-endian, so a
    // lexicographic compare is the integer compare.
    if s_bytes >= &Q[..] {
        return None;
    }
    let mut arr = [0u8; 32];
    arr.copy_from_slice(s_bytes);
    let s = scalar_from_bytes(&arr)?;
    Some((gamma, c, s))
}

/// RFC 9381 §5.1: ECVRF_prove. Returns the ptLen+cLen+qLen = 81-byte proof.
pub fn prove(sk: &[u8; 32], pk_string: &[u8], alpha: &[u8]) -> Vec<u8> {
    #[cfg(test)]
    PROVE_COUNT.with(|c| c.set(c.get().wrapping_add(1)));
    let x = scalar_from_bytes(sk).expect("the secret scalar must be valid");
    let y = generator() * &x;
    let y_affine = y.to_affine();
    let h = encode_to_curve(pk_string, alpha);
    let h_string = point_to_string(&h);
    let gamma = (ProjectivePoint::from(h) * &x).to_affine();
    let k = nonce_generation(sk, &h_string);
    let u = (generator() * &k).to_affine();
    let v = (ProjectivePoint::from(h) * &k).to_affine();
    let c = challenge_generation(&y_affine, &h, &gamma, &u, &v);
    let s = k + scalar_from_int(c) * &x;
    let s_bytes = s.to_bytes();
    let mut out = Vec::with_capacity(PTLEN + CLEN + QLEN);
    out.extend_from_slice(&point_to_string(&gamma));
    out.extend_from_slice(&int_to_string(c, CLEN));
    for i in 0..QLEN {
        out.push(s_bytes[i]);
    }
    out
}

/// The public key as a curve point, y = x·B. RFC 9381 §5.1 calls this Y.
///
/// This exists to be HOISTED out of a loop: `assign_tasks` proves over many
/// task ids with one fixed secret key, and `prove()` recomputes y from sk on
/// every call because the standard's function signature takes only (sk,
/// alpha). That is one of prove()'s four scalar multiplications spent
/// re-deriving a value the caller already knows. `prove_with_public_key`
/// below takes y as an argument so the caller pays for it once per key
/// instead of once per task — about 0.196 ms of the 0.87 ms a prove costs,
/// which is ~22% of the mining loop's VRF cost.
///
/// **This is not an optimisation of the VRF.** The output is the function of
/// (sk, alpha) it always was; the change is where one group operation is
/// *performed*, not what it computes. Nothing about the construction,
/// constant-time behaviour or security argument changes, because no
/// computation is removed — the same y is multiplied in either way, and a
/// caller that passes a y not equal to x·B produces a proof `verify` rejects,
/// exactly as a caller passing the wrong sk would.
pub fn public_key_point(sk: &[u8; 32]) -> AffinePoint {
    let x = scalar_from_bytes(sk).expect("the secret scalar must be valid");
    (generator() * &x).to_affine()
}

/// `prove()` with the public key point supplied, so a loop over many alphas
/// with one key computes y once instead of once per alpha. Output-identical
/// to `prove()` — see `a_cached_public_key_gives_the_byte_identical_proof`
/// in the tests, which locks that equivalence against the RFC vectors.
///
/// **Safety of the hoisting, stated plainly:** y is a pure function of sk,
/// and the caller supplies sk as well, so the cached y can disagree with sk
/// only if the caller is inconsistent — in which case the resulting proof
/// fails verification, because `verify` recomputes y from the public key it
/// was given. The failure mode is a rejected proof, not an accepted wrong
/// one, which is why this needs no new trust: it cannot make a bad proof
/// verify, only avoid recomputing a good one.
pub fn prove_with_public_key(
    sk: &[u8; 32],
    pk_string: &[u8],
    y: &AffinePoint,
    alpha: &[u8],
) -> Vec<u8> {
    #[cfg(test)]
    PROVE_COUNT.with(|c| c.set(c.get().wrapping_add(1)));
    let x = scalar_from_bytes(sk).expect("the secret scalar must be valid");
    let y_affine = *y;
    let h = encode_to_curve(pk_string, alpha);
    let h_string = point_to_string(&h);
    let gamma = (ProjectivePoint::from(h) * &x).to_affine();
    let k = nonce_generation(sk, &h_string);
    let u = (generator() * &k).to_affine();
    let v = (ProjectivePoint::from(h) * &k).to_affine();
    let c = challenge_generation(&y_affine, &h, &gamma, &u, &v);
    let s = k + scalar_from_int(c) * &x;
    let s_bytes = s.to_bytes();
    let mut out = Vec::with_capacity(PTLEN + CLEN + QLEN);
    out.extend_from_slice(&point_to_string(&gamma));
    out.extend_from_slice(&int_to_string(c, CLEN));
    for i in 0..QLEN {
        out.push(s_bytes[i]);
    }
    out
}

/// RFC 9381 §5.2: beta from a proof. Only call this on a proof that
/// ECVRF_verify has accepted — beta is the random output, and deriving it
/// from an unverified proof is exactly what pseudorandomness forbids.
pub fn proof_to_hash(pi: &[u8]) -> Option<[u8; 32]> {
    let (gamma, _, _) = decode_proof(pi)?;
    // cofactor is 1, so cofactor*Gamma == Gamma
    let gamma_string = point_to_string(&gamma);
    Some(hash_chunks(&[&[SUITE, 0x03], &gamma_string, &[0x00]]))
}

/// RFC 9381 §5.3: ECVRF_verify. Returns Some(beta) on accept, None on
/// reject. Total on adversarial input.
pub fn verify(pk_string: &[u8], alpha: &[u8], pi: &[u8]) -> Option<[u8; 32]> {
    let y_affine = string_to_point(pk_string)?;
    let y = ProjectivePoint::from(y_affine);
    let (gamma, c, s) = decode_proof(pi)?;
    let h = encode_to_curve(pk_string, alpha);
    // U = s*B - c*Y ; V = s*H - c*Gamma (RFC 9381 writes it this way; the
    // prover computed U = k*B and V = k*H, and s = k + c*x makes them equal)
    let s_b = generator() * &s;
    let c_y = y * &scalar_from_int(c);
    let u = (s_b - c_y).to_affine();
    let s_h = ProjectivePoint::from(h) * &s;
    let c_gamma = ProjectivePoint::from(gamma) * &scalar_from_int(c);
    let v = (s_h - c_gamma).to_affine();
    let c_prime = challenge_generation(&y_affine, &h, &gamma, &u, &v);
    if c == c_prime {
        proof_to_hash(pi)
    } else {
        None
    }
}

