//! ECVRF — RFC 9381, ciphersuite ECVRF-P256-SHA256-TAI.
//!
//! This replaces the HMAC-toy VRF that stood in for the assignment seed
//! while the real construction was not yet written. The toy guaranteed
//! only determinism; a VRF must also guarantee UNIQUENESS (for a fixed
//! public key and input, at most one output verifies) and
//! PSEUDORANDOMNESS (the output is indistinguishable from random without
//! the proof). An HMAC of (sk, input) has neither: anyone who sees one
//! output cannot check it, and two provers cannot agree it is a function.
//!
//! WHY P-256 AND NOT secp256k1: RFC 9381 defines ciphersuites only for
//! P-256 and edwards25519. secp256k1 would be a bespoke, unaudited suite;
//! P-256-SHA256-TAI is a named, standard one, which is why it is here.
//!
//! CORRECTNESS ANCHOR: the three test vectors from RFC 9381 Appendix B.1
//! (Examples 10-12) are reproduced byte-for-byte in the tests below. If
//! this module ever drifts from the standard, those fail. That is a
//! stronger check than any self-consistency test, because the vectors were
//! generated by the reference implementation at github.com/reyzin/ecvrf.
//!
//! IP NOTE (honest gap, not a claim): the ECVRF CONSTRUCTION is an open
//! IRTF CFRG standard (RFC 9381, Informational). Patent reconnaissance
//! found 69 patents around "verifiable random function" + Algorand, but
//! the top results cover VRF-USING blockchain systems (leader selection,
//! transaction propagation), not the ECVRF construction itself. The IETF
//! IPR disclosure page for the VRF draft could NOT be fetched (Cloudflare
//! 403), so the absence of a declaration is UNVERIFIED, not confirmed.
//! KÖK's mitigating structural fact: it uses the VRF only to seed U-layer
//! TASK ASSIGNMENT; leader selection is the MatMul PoW G layer, which does
//! not use a VRF at all — so the use sits outside the leader-selection
//! patent cluster that dominates the 69 results.

